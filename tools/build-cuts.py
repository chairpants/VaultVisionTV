#!/usr/bin/env python3
"""Build data/cuts.js — quiet moments a commercial break can cut in on.

Nothing in the catalog says where a programme's original act breaks were, so
scheduler.js splits a programme evenly and then, where this file knows of one,
moves each cut to a nearby pause in the dialogue. The pauses come from the
captions VaultVision bundles: a stretch with no caption cue for several seconds
is usually a scene change, a music sting or an establishing shot — a far better
place to cut than the middle of a sentence.

Only shows with bundled captions get entries (a handful today); every other
programme keeps its even split. Re-run after VaultVision gains captions:

    python tools/build-cuts.py ../VaultVision
"""
import json
import re
import sys
import time
from pathlib import Path

ROOT = Path(__file__).parent.parent
CATALOG_JSON = ROOT / "data" / "catalog.json"
OUT_JS = ROOT / "data" / "cuts.js"

MIN_GAP_SEC = 4.0       # shorter silences are just people breathing
LEAD_IN_SEC = 1.0       # cut this long before the next line starts
NEIGHBOURHOOD_SEC = 45  # keep only the longest pause in any stretch this long
# Recordings scheduler.js never interrupts (NO_MID_BREAK_GENRES): no use
# shipping cut points for them.
SKIP_GENRES = {"Broadcast Blocks"}

CUE = re.compile(r"(?:(\d+):)?(\d\d):(\d\d)[.,](\d{3})\s*-->\s*(?:(\d+):)?(\d\d):(\d\d)[.,](\d{3})")


def seconds(h, m, s, ms):
    return int(h or 0) * 3600 + int(m) * 60 + int(s) + int(ms) / 1000


def cuts_for(vtt):
    cues = sorted((seconds(*m.groups()[:4]), seconds(*m.groups()[4:])) for m in CUE.finditer(vtt))
    pauses = []  # (length, cut time)
    spoken_until = None
    for start, end in cues:
        if spoken_until is not None and start - spoken_until >= MIN_GAP_SEC:
            pauses.append((start - spoken_until, start - LEAD_IN_SEC))
        spoken_until = end if spoken_until is None else max(spoken_until, end)
    # Longest first, each claiming its neighbourhood: scheduler.js takes the
    # nearest candidate to where it wanted to cut, so thinning here is what
    # makes "nearest" mean "the best pause around there".
    kept = []
    for _, at in sorted(pauses, reverse=True):
        if all(abs(at - other) >= NEIGHBOURHOOD_SEC for other in kept):
            kept.append(at)
    return sorted(round(at) for at in kept)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    library = Path(sys.argv[1])
    catalog = json.loads(CATALOG_JSON.read_text(encoding="utf-8"))

    cuts = {}
    shows = []
    for show_id, show in sorted(catalog["shows"].items()):
        if show.get("genre") in SKIP_GENRES:
            continue
        captions_js = library / "shows" / show_id / "captions.js"
        if not captions_js.exists() or captions_js.stat().st_size < 200:
            continue
        text = captions_js.read_text(encoding="utf-8-sig")
        try:
            captions = json.loads(text[text.index("{"):text.rindex("}") + 1])
        except ValueError as e:
            print(f"  {show_id}: captions.js is not plain JSON ({e}) -- skipped")
            continue
        found = 0
        for episode in show["episodes"]:
            vtt = captions.get(episode["key"])
            points = cuts_for(vtt) if vtt else []
            if points:
                cuts[episode["key"]] = points
                found += 1
        if found:
            shows.append(show_id)
            print(f"  {show_id}: {found}/{len(show['episodes'])} episodes")

    header = (
        "// Generated by tools/build-cuts.py — do not edit by hand.\n"
        f"// {time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime())}; "
        f"{len(cuts)} episodes of {', '.join(shows) or 'no shows'}.\n"
        "// episode key -> seconds into the file where a break may cut in.\n"
    )
    # .js not .json for the same reason catalog.js exists — file:// pages can't
    # fetch() a local file, so the app loads it as a plain <script src>.
    body = ",\n".join(f" {json.dumps(k)}: {json.dumps(v, separators=(',', ':'))}" for k, v in sorted(cuts.items()))
    OUT_JS.write_text(f"{header}window.CUTS = {{\n{body}\n}};\n", encoding="utf-8")
    print(f"wrote {OUT_JS} — cut points for {len(cuts)} episodes across {len(shows)} shows")


if __name__ == "__main__":
    main()
